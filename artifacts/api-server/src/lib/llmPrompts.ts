export function featureInstruction(feature: PromptFeature): string {
  return FEATURE_PROMPTS[feature].instruction;
}

export function buildLlmMessages(input: { instruction: string; context: Record<string, unknown> }) {
  return [
    { role: "system" as const, content: `${COMMON_LLM_RULES}\n\nTask instructions:\n${input.instruction}` },
    { role: "user" as const, content: JSON.stringify(input.context) },
  ];
}
